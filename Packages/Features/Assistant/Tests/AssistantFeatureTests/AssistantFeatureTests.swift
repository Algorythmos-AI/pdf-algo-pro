@MainActor
private final class Revealed {
  var citations: [Citation] = []
}

@MainActor
private func makeModel(
  task: AssistantTask, intelligence: any DocumentIntelligence = FakeIntelligence(),
  telemetry: RecordingTelemetry = RecordingTelemetry()
) -> (AssistantModel, Revealed) {
  let revealed = Revealed()
  let model = AssistantModel(
    task: task, intelligence: intelligence, pages: { [PageText(pageIndex: 0, text: "testing")] }, telemetry: telemetry,
    onReveal: { revealed.citations.append($0) })
  return (model, revealed)
}

/// An intelligence whose results wait until the test releases them, and that finishes even when
/// cancelled, as an on-device model can.
private actor GatedIntelligence: DocumentIntelligence {
  private var waiting: [AssistantTask: CheckedContinuation<Void, Never>] = [:]

  func isWaiting(_ task: AssistantTask) -> Bool { waiting[task] != nil }
  func release(_ task: AssistantTask) { waiting.removeValue(forKey: task)?.resume() }

  func availability() async -> IntelligenceAvailability { .available(.onDevice) }
  func summarize(_ pages: [PageText]) async throws -> Answer {
    await gate(.summarize)
    return grounded("Summary")
  }
  func answer(_ question: String, from pages: [PageText]) async throws -> Answer {
    await gate(.ask)
    return grounded(question)
  }
  func extractFields(from pages: [PageText]) async throws -> Extraction {
    await gate(.extract)
    return Extraction(fields: [], tier: .onDevice)
  }
  func explainContract(_ pages: [PageText]) async throws -> Answer {
    await gate(.explainContract)
    return grounded("Contract")
  }

  private func gate(_ task: AssistantTask) async {
    await withCheckedContinuation { waiting[task] = $0 }
  }

  private func grounded(_ text: String) -> Answer {
    Answer(text: text, citations: [Citation(pageIndex: 0, quote: "testing")], tier: .onDevice, isGrounded: true)
  }
}

/// An intelligence that says whether it can run only when the test lets it, and counts the requests
/// that reach it.
private actor SlowAvailability: DocumentIntelligence {
  private var waiting: CheckedContinuation<Void, Never>?
  private(set) var requests = 0

  var isAsked: Bool { waiting != nil }
  func answerAvailability() {
    waiting?.resume()
    waiting = nil
  }

  func availability() async -> IntelligenceAvailability {
    await withCheckedContinuation { waiting = $0 }
    return .available(.onDevice)
  }
  func summarize(_ pages: [PageText]) async throws -> Answer { respond() }
  func answer(_ question: String, from pages: [PageText]) async throws -> Answer { respond() }
  func extractFields(from pages: [PageText]) async throws -> Extraction {
    requests += 1
    return Extraction(fields: [], tier: .onDevice)
  }
  func explainContract(_ pages: [PageText]) async throws -> Answer { respond() }

  private func respond() -> Answer {
    requests += 1
    return Answer(
      text: "answer", citations: [Citation(pageIndex: 0, quote: "testing")], tier: .onDevice, isGrounded: true)
  }
}

/// The footer on text that leaves the app, in English (EU AI Act Art 50(2), plan item L3).
private let footer = "Generated by PDF Algo Pro from this document; may contain errors."

/// The records of RFC 4180 text whose cells are separated by `separator`, or `nil` when the text is not
/// valid CSV: a quote inside an unquoted cell, text after a closing quote, a bare line feed, an unclosed
/// quote or a last record not ended by CRLF.
private func csvRecords(_ text: String, separator: Unicode.Scalar = ",") -> [[String]]? {
  var records: [[String]] = []
  var record: [String] = []
  var cell = ""
  var isQuoted = false
  var afterQuote = false
  var scalars = Array(text.unicodeScalars)[...]
  while let scalar = scalars.popFirst() {
    if isQuoted {
      if scalar != "\"" {
        cell.unicodeScalars.append(scalar)
      } else if scalars.first == "\"" {
        scalars.removeFirst()
        cell.unicodeScalars.append(scalar)
      } else {
        isQuoted = false
        afterQuote = true
      }
    } else if scalar == "\"" {
      guard cell.isEmpty, !afterQuote else { return nil }
      isQuoted = true
    } else if scalar == separator {
      record.append(cell)
      cell = ""
      afterQuote = false
    } else if scalar == "\r" {
      guard scalars.popFirst() == "\n" else { return nil }
      record.append(cell)
      records.append(record)
      record = []
      cell = ""
      afterQuote = false
    } else {
      guard !afterQuote, scalar != "\n" else { return nil }
      cell.unicodeScalars.append(scalar)
    }
  }
  return isQuoted || afterQuote || !record.isEmpty || !cell.isEmpty ? nil : records
}

/// How many times `footer` occurs in `text`.
private func footerCount(in text: String) -> Int {
  text.components(separatedBy: footer).count - 1
}

@MainActor
private func waitUntil(_ condition: () async -> Bool) async throws {
  for _ in 0..<400 {
    if await condition() { return }
    try await Task.sleep(for: .milliseconds(5))
  }
  Issue.record("The condition never held")
}

@MainActor
@Suite("Assistant model")
struct AssistantModelTests {
  @Test("Summaries run straight away and cite their pages (FR-AI-001)")
  func summary() async throws {
    let telemetry = RecordingTelemetry()
    let (model, revealed) = makeModel(task: .summarize, telemetry: telemetry)
    await model.start()
    guard case .answered(let answer) = model.phase else { throw Failure.unexpected }
    #expect(answer.isGrounded && answer.citations.map(\.pageIndex) == [0])
    model.reveal(answer.citations[0])
    #expect(revealed.citations == answer.citations)
    #expect(model.shareableText == "The document is about testing.\n\nSources: p. 1\n\n\(footer)")
    await model.recordKept()
    #expect(await telemetry.events == ["intelligence.request.completed", "intelligence.answer.kept"])
  }

  @Test("Closing the assistant while it is still starting runs nothing (#271)")
  func closingDuringStartRunsNothing() async throws {
    let intelligence = SlowAvailability()
    let (model, _) = makeModel(task: .summarize, intelligence: intelligence)
    let starting = Task { await model.start() }
    try await waitUntil { await intelligence.isAsked }
    // The sheet closed while the assistant was asking whether intelligence can run.
    model.cancel()
    await intelligence.answerAvailability()
    await starting.value
    #expect(await intelligence.requests == 0)
    #expect(model.phase == .idle)
  }

  @Test("Ask waits for a question and ignores blank ones (FR-AI-002)")
