  @Test(
    "Copied and shared answers end with the generated footer, once, after a blank line (Art 50(2), L3)",
    arguments: [AssistantTask.summarize, .ask, .explainContract])
  func answerFooter(task: AssistantTask) async throws {
    let (model, _) = makeModel(task: task)
    await model.start()
    if task == .ask {
      model.question = "What is tested?"
      await model.ask()
    }
    // Copy and the toolbar's Share both hand out `shareableText`.
    let text = try #require(model.shareableText, "Nothing to share in phase \(model.phase)")
    #expect(AssistantModel.generatedFooter == footer, "The footer is \(AssistantModel.generatedFooter)")
    #expect(text.hasSuffix("\n\nSources: p. 1\n\n" + footer), "The shared text is \(text.debugDescription)")
    #expect(footerCount(in: text) == 1, "The shared text is \(text.debugDescription)")
  }

  @Test("Copied and shared CSV ends with the footer as one last row and stays valid CSV (Art 50(2), L3)")
  func csvFooter() async throws {
    let extraction = Extraction(
      fields: [
        ExtractedField(key: "seller", value: "Acme \"Ltd\", Paris; France", pageIndex: 0),
        ExtractedField(key: "total", value: "1 234,56", pageIndex: nil),
      ], tier: .onDevice)
    let (model, _) = makeModel(task: .extract, intelligence: FakeIntelligence(extraction: extraction))
    await model.start()
    // Copy as CSV and the toolbar's Share both hand out `shareableText`.
    let text = try #require(model.shareableText, "Nothing to share in phase \(model.phase)")
    let expected = [
      ["field", "value", "page"], ["seller", "Acme \"Ltd\", Paris; France", "1"], ["total", "1 234,56", ""],
      ["notice", footer, ""],
    ]
    #expect(csvRecords(text) == expected, "The copied CSV is \(text.debugDescription)")
    #expect(footerCount(in: text) == 1, "The copied CSV is \(text.debugDescription)")

    // Share as CSV file: a byte order mark, then the locale's separator; French uses semicolons, which
    // the quoted footer also contains.
    for (identifier, separator) in [("en_AU", Unicode.Scalar(",")), ("fr_FR", ";")] {
      let file = CSVFile(extraction, name: "Extracted fields", notice: footer, locale: Locale(identifier: identifier))
      #expect(file.name == "Extracted fields.csv")
      #expect(file.data.prefix(3) == Data([0xEF, 0xBB, 0xBF]))
      let fileText = try #require(String(data: file.data.dropFirst(3), encoding: .utf8))
      #expect(csvRecords(fileText, separator: separator) == expected, "\(identifier): \(fileText.debugDescription)")
      #expect(footerCount(in: fileText) == 1, "\(identifier): \(fileText.debugDescription)")
    }
  }

