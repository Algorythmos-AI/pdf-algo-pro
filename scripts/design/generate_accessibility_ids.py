#!/usr/bin/env python3
"""Generate the accessibility identifiers from design/accessibility-ids.json. Standard library only.

    python3 scripts/design/generate_accessibility_ids.py           # write the generated file
    python3 scripts/design/generate_accessibility_ids.py --check   # CI: fail if the file is stale or a rule is broken

The app sets these identifiers on its controls and the UI tests find controls by them, so both sides
read one list (docs/testing-strategy.md, "Accessibility identifiers"). Each identifier is a dotted path,
and the dots become nested enums: `reader.markup.paste` is `AccessibilityID.Reader.Markup.paste`, and
`reader.markup` is `AccessibilityID.Reader.markup`. A last part in braces is a value supplied where the
identifier is used, and the identifier becomes a function: `library.document.{title}` is
`AccessibilityID.Library.document(_ title: String)`, and `{page:Int}` takes an `Int`.

Rules checked on every run:
  * the list is sorted, and no identifier appears twice;
  * every part is lower camel case (letters and digits, starting with a lower-case letter), except a
    last part in braces;
  * a part in braces names its value, optionally with the type `Int` or `String`, and comes last.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "design" / "accessibility-ids.json"
OUTPUT = ROOT / "Packages" / "Core" / "Sources" / "AccessibilityIDs" / "Generated" / "AccessibilityIDs.swift"
PART = re.compile(r"^[a-z][A-Za-z0-9]*$")
VALUE = re.compile(r"^\{([a-z][A-Za-z0-9]*)(?::(Int|String))?\}$")
# Words Swift reserves in a declaration; a member with one of these names is declared in backticks and
# used without them after a dot (`AccessibilityID.Onboarding.continue`).
KEYWORDS = {
    "as", "associatedtype", "break", "case", "catch", "class", "continue", "default", "defer", "deinit", "do",
    "else", "enum", "extension", "fallthrough", "false", "fileprivate", "for", "func", "guard", "if", "import",
    "in", "init", "inout", "internal", "is", "let", "nil", "open", "operator", "private", "protocol", "public",
    "repeat", "rethrows", "return", "self", "static", "struct", "subscript", "super", "switch", "throw",
    "throws", "true", "try", "typealias", "var", "where", "while",
}
HEADER = """\
// Generated by scripts/design/generate_accessibility_ids.py from design/accessibility-ids.json.
// Do not edit: change the list and run the script (docs/testing-strategy.md).
"""


def validate(ids: list[str]) -> list[str]:
    """Every broken rule, as a sentence; an empty list when the identifiers are sound."""
    errors: list[str] = []
    if ids != sorted(ids):
        errors.append("the identifiers are not sorted")
    seen: set[str] = set()
    for identifier in ids:
        if identifier in seen:
            errors.append(f"{identifier!r} appears twice")
        seen.add(identifier)
        parts = identifier.split(".")
        if len(parts) < 2:
            errors.append(f"{identifier!r} needs a screen and a name, such as 'reader.more'")
        for index, part in enumerate(parts):
            if VALUE.match(part):
                if index != len(parts) - 1:
                    errors.append(f"{identifier!r}: a value in braces can only be the last part")
                elif len(parts) < 3:
                    errors.append(f"{identifier!r}: a value in braces needs a screen and a name before it")
            elif not PART.match(part):
                errors.append(f"{identifier!r}: {part!r} is not lower camel case")
    return errors


def swift_name(part: str) -> str:
    return f"`{part}`" if part in KEYWORDS else part


def enum_name(part: str) -> str:
    return part[0].upper() + part[1:]


def build_tree(ids: list[str]) -> dict:
    """Nested dicts: each key is a part; `None` under the key `""` marks an identifier ending there."""
    tree: dict = {}
    for identifier in ids:
        parts = identifier.split(".")
        node = tree
        for part in parts[:-1]:
            node = node.setdefault(part, {})
        node.setdefault("", []).append((parts[-1], identifier))
    return tree


def render_node(name: str, node: dict, path: list[str], depth: int) -> list[str]:
    pad = "  " * depth
    inner = "  " * (depth + 1)
    dotted = ".".join(path)
    lines = [f"{pad}/// The identifiers under `{dotted}`.", f"{pad}public enum {enum_name(name)} {{"]
    members: list[str] = []
    for last, identifier in sorted(node.get("", []), key=lambda item: item[1]):
        value = VALUE.match(last)
        if value:
            label = value.group(1)
            kind = value.group(2) or "String"
            prefix = identifier[: identifier.rindex(".")]
            parent = prefix.split(".")[-1]
            members += [
                f"{inner}/// The identifier `{identifier}`, for the `{label}` given.",
                f"{inner}public static func {swift_name(parent)}(_ {label}: {kind}) -> String {{",
                f'{inner}  "{prefix}.\\({label})"',
                f"{inner}}}",
            ]
        else:
            members += [
                f"{inner}/// The identifier `{identifier}`.",
                f'{inner}public static let {swift_name(last)} = "{identifier}"',
            ]
    children = sorted(key for key in node if key)
    for child in children:
        if members:
            members.append("")
        members += render_node(child, node[child], path + [child], depth + 1)
    lines += members
    lines.append(f"{pad}}}")
    return lines


def render(ids: list[str]) -> str:
    tree = build_tree(ids)
    # A function for `a.b.{value}` sits in `A`, not in an enum `B` of its own.
    hoisted: dict = {}
    for identifier in ids:
        parts = identifier.split(".")
        if VALUE.match(parts[-1]):
            node = tree
            for part in parts[:-2]:
                node = node[part]
            holder = node[parts[-2]]
            holder[""].remove((parts[-1], identifier))
            if not holder[""]:
                del holder[""]
            if not holder:
                del node[parts[-2]]
            node.setdefault("", []).append((parts[-1], identifier))
            hoisted[identifier] = True
    lines = HEADER.splitlines() + [
        "",
        "/// The accessibility identifiers the app sets on its controls and its UI tests find them by.",
        "///",
        "/// One list serves both, so a renamed control cannot leave a test looking for the old name, and",
        "/// French runs use the same tests as English ones. Each identifier's value is its dotted path.",
        "public enum AccessibilityID {",
    ]
    body: list[str] = []
    for top in sorted(tree):
        if not top:
            continue
        if body:
            body.append("")
        body += render_node(top, tree[top], [top], 1)
    lines += body
    lines.append("}")
    return "\n".join(lines) + "\n"


def load() -> list[str]:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    ids = data.get("identifiers")
    if not isinstance(ids, list) or not all(isinstance(item, str) for item in ids):
        raise SystemExit(f"{SOURCE.relative_to(ROOT)}: 'identifiers' must be a list of strings")
    return ids


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    check = "--check" in argv
    ids = load()
    errors = validate(ids)
    if errors:
        for error in errors:
            print(f"::error::{SOURCE.relative_to(ROOT)}: {error}")
        return 1
    text = render(ids)
    if check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(
                f"::error::{OUTPUT.relative_to(ROOT)} is stale: run python3 scripts/design/generate_accessibility_ids.py"
            )
            return 1
        print(f"accessibility identifiers: {len(ids)}, generated file up to date")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(ids)} identifiers)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
