#!/usr/bin/env python3
"""Build the snapshot gallery, docs/design/gallery.md, from the snapshot references. Standard library only.

    python3 scripts/design/gallery.py           # write the gallery
    python3 scripts/design/gallery.py --check   # fail if the gallery does not match the references

The references are the images the snapshot tests compare against (App/Tests/SnapshotTests.swift),
recorded on the pinned CI simulator and kept under App/Tests/__Snapshots__/<suite>/ as
`<test>.<variant>.png`. The gallery has one table per screen (a test) and one column per variant, each
cell an image linked relative to the gallery, so it renders on GitHub and in any Markdown viewer
without a build. It is part of the design pass that closes readiness blocker C5 (PAP-070), beside
docs/design/design-pass-checklist.md.
"""
from __future__ import annotations

import re
import sys
from dataclasses import dataclass
from os.path import relpath
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SNAPSHOTS = ROOT / "App" / "Tests" / "__Snapshots__"
OUTPUT = ROOT / "docs" / "design" / "gallery.md"
REFERENCE = re.compile(r"^(?P<test>[A-Za-z][A-Za-z0-9_]*)\.(?P<variant>[A-Za-z][A-Za-z0-9_]*)\.png$")
# The variants the snapshot tests record, in the order they are shown, with their column headings.
# A variant not listed here follows them, in name order, under a heading made from its name.
VARIANTS = {
    "light": "Light",
    "dark": "Dark",
    "largeText": "Accessibility XL text",
}


@dataclass(frozen=True)
class Reference:
    """One recorded reference image."""

    suite: str
    test: str
    variant: str
    path: Path


def words(name: str) -> str:
    """A camel-case name as words in sentence case: `paywallWithoutTrial` is "Paywall without trial"."""
    spaced = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", name).replace("_", " ")
    lowered = " ".join(part if part.isupper() and len(part) > 1 else part.lower() for part in spaced.split())
    return lowered[:1].upper() + lowered[1:]


def references(folder: Path = SNAPSHOTS) -> tuple[list[Reference], list[str]]:
    """Every reference under `folder`, and the files there that are not named as a reference."""
    found: list[Reference] = []
    unnamed: list[str] = []
    if not folder.is_dir():
        return found, unnamed
    for path in sorted(folder.rglob("*")):
        if not path.is_file() or path.name.startswith("."):
            continue
        match = REFERENCE.match(path.name)
        if match and path.parent != folder:
            found.append(Reference(path.parent.name, match["test"], match["variant"], path))
        else:
            unnamed.append(str(path.relative_to(folder)))
    return found, unnamed


def variant_order(variants: set[str]) -> list[str]:
    """Known variants first, in their order, then any others by name."""
    known = [v for v in VARIANTS if v in variants]
    return known + sorted(variants - set(VARIANTS))


def render(found: list[Reference], output: Path = OUTPUT) -> str:
    """The gallery's Markdown for these references, with image links relative to `output`."""
    lines = [
        "# Snapshot gallery",
        "",
        "Owner: Design · Reviewed: whenever a snapshot reference is recorded again, and at each milestone",
        "",
        "Generated by [`scripts/design/gallery.py`](../../scripts/design/gallery.py) from the snapshot references",
        "under `App/Tests/__Snapshots__/`; do not edit it by hand. After the references are recorded again",
        "(a manual `ci.yml` run with `record_snapshots`, see the [testing strategy](../testing-strategy.md)),",
        "run `python3 scripts/design/gallery.py` and commit the result with them.",
        "",
        "Each table is one screen as a snapshot test draws it on the pinned simulator, and each column one",
        "appearance. It is the visual record for the [design-pass checklist](design-pass-checklist.md),",
        "which closes readiness blocker C5 with the owner's walk-through (PAP-070).",
    ]
    if not found:
        lines += ["", "No snapshot references are recorded yet."]
        return "\n".join(lines) + "\n"
    suites = sorted({r.suite for r in found})
    for suite in suites:
        in_suite = [r for r in found if r.suite == suite]
        if len(suites) > 1:
            lines += ["", f"## {words(suite)}"]
        heading = "###" if len(suites) > 1 else "##"
        for test in sorted({r.test for r in in_suite}, key=str.lower):
            by_variant = {r.variant: r for r in in_suite if r.test == test}
            order = variant_order(set(by_variant))
            title = words(test)
            lines += [
                "",
                f"{heading} {title}",
                "",
                f"`{suite}/{test}`",
                "",
                "| " + " | ".join(VARIANTS.get(v, words(v)) for v in order) + " |",
                "|" + "---|" * len(order),
            ]
            cells = []
            for variant in order:
                link = Path(relpath(by_variant[variant].path, output.parent)).as_posix()
                label = VARIANTS.get(variant, words(variant))
                alt = f"{title}, {label[:1].lower()}{label[1:]}"
                cells.append(f'<img src="{link}" width="220" alt="{alt}">')
            lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    found, unnamed = references()
    for name in unnamed:
        print(f"::warning::{name} is not named <test>.<variant>.png in a suite folder; left out of the gallery")
    text = render(found)
    if check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run python3 scripts/design/gallery.py and commit it")
            return 1
        print(f"gallery: {len(found)} reference(s), up to date")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"gallery: wrote {OUTPUT.relative_to(ROOT)} with {len(found)} reference(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
